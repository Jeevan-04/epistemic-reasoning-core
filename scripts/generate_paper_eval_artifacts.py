#!/usr/bin/env python3
"""Generate paper-ready LaTeX tables and pipeline figure snippets.

Inputs:
- tests/logs/bench_compare_results.json
- tests/logs/aggregated_outputs/pipeline_outcomes.jsonl

Outputs:
- paper/generated_eval_tables.tex
- tests/logs/pipeline_localization_summary.json
"""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
LOG_DIR = ROOT / "tests" / "logs"
IN_SUMMARY = LOG_DIR / "bench_compare_results.json"
IN_PIPELINE = LOG_DIR / "aggregated_outputs" / "pipeline_outcomes.jsonl"
OUT_TEX = ROOT / "paper" / "generated_eval_tables.tex"
OUT_PIPELINE_JSON = LOG_DIR / "pipeline_localization_summary.json"


def latex_escape(text: str) -> str:
    escaped = (
        text.replace("\\", "\\textbackslash{}")
        .replace("_", "\\_")
        .replace("%", "\\%")
        .replace("&", "\\&")
        .replace("#", "\\#")
    )
    return escaped


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf8"))


def read_jsonl(path: Path) -> list[dict]:
    rows = []
    for line in path.read_text(encoding="utf8").splitlines():
        line = line.strip()
        if not line:
            continue
        rows.append(json.loads(line))
    return rows


def compute_pipeline_counts(rows: list[dict]) -> dict:
    nl_rows = [r for r in rows if not str(r.get("id", "")).startswith("sym-")]
    sym_rows = [r for r in rows if str(r.get("id", "")).startswith("sym-")]

    def counts(group: list[dict], include_parse: bool) -> dict:
        total = len(group)
        parse_success = sum(1 for r in group if r.get("pipeline_outcome", {}).get("parse_success") is True)
        grounding_success = sum(1 for r in group if r.get("pipeline_outcome", {}).get("grounding_success") is True)
        argument_construction = sum(1 for r in group if r.get("pipeline_outcome", {}).get("argument_construction") is True)
        reasoning_executed = sum(1 for r in group if r.get("pipeline_outcome", {}).get("reasoning_executed") is True)
        decisive = sum(
            1
            for r in group
            if r.get("pipeline_outcome", {}).get("final_verdict") not in (None, "unknown")
        )
        unknown = sum(
            1
            for r in group
            if r.get("pipeline_outcome", {}).get("final_verdict") == "unknown"
        )
        result = {
            "total": total,
            "grounding_success": grounding_success,
            "argument_construction": argument_construction,
            "reasoning_executed": reasoning_executed,
            "decisive_verdicts": decisive,
            "unknown_verdicts": unknown,
        }
        if include_parse:
            result["parse_success"] = parse_success
        return result

    return {
        "nl_integrated": counts(nl_rows, include_parse=True),
        "symbolic": counts(sym_rows, include_parse=False),
    }


def format_pct(value) -> str:
    if isinstance(value, str):
        return latex_escape(value)
    return f"{value:.1f}"


def generate_tex(summary: dict, pipeline: dict) -> str:
    by_category = summary.get("by_category", {})
    by_mode = summary.get("by_mode", {})
    failure_distribution = summary.get("failure_distribution", [])

    lines = []
    lines.append("% Auto-generated by scripts/generate_paper_eval_artifacts.py")
    lines.append("\\subsection{Category-Wise Split Evaluation}")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\begin{tabular}{lrrrrrrr}")
    lines.append("\\toprule")
    lines.append("Category & Count & Parse \\% & Ground \\% & Reason \\% & Avg Args & Avg Attacks & Replay \\% \\\\")
    lines.append("\\midrule")
    for category in sorted(by_category.keys()):
        s = by_category[category]
        lines.append(
            f"{latex_escape(category)} & {s['count']} & {format_pct(s['parse_success_pct'])} & {format_pct(s['grounding_success_pct'])} & {format_pct(s['reasoning_success_pct'])} & {s['avg_args']} & {s['avg_attacks']} & {format_pct(s['replay_verified_pct'])} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\caption{Category-wise stage metrics under the split-evaluation protocol.}")
    lines.append("\\label{tab:category_split_eval}")
    lines.append("\\end{table}")
    lines.append("")

    lines.append("\\subsection{Mode Comparison}")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\begin{tabular}{lrrrrrrr}")
    lines.append("\\toprule")
    lines.append("Mode & Count & Parse \\% & Ground \\% & Reason \\% & Avg Args & Avg Attacks & Replay \\% \\\\")
    lines.append("\\midrule")
    for mode in sorted(by_mode.keys()):
        s = by_mode[mode]
        lines.append(
            f"{latex_escape(mode)} & {s['count']} & {format_pct(s['parse_success_pct'])} & {format_pct(s['grounding_success_pct'])} & {format_pct(s['reasoning_success_pct'])} & {s['avg_args']} & {s['avg_attacks']} & {format_pct(s['replay_verified_pct'])} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\caption{Controlled symbolic vs integrated natural-language evaluation.}")
    lines.append("\\label{tab:mode_comparison}")
    lines.append("\\end{table}")
    lines.append("")

    lines.append("\\subsection{Pipeline Localization Figure}")
    nl = pipeline["nl_integrated"]
    sym = pipeline["symbolic"]
    lines.append("\\begin{figure}[t]")
    lines.append("\\centering")
    lines.append("\\fbox{\\begin{minipage}{0.47\\linewidth}")
    lines.append("\\centering")
    lines.append("\\textbf{Integrated NL Pipeline (n=" + str(nl["total"]) + ")}\\\\")
    lines.append(str(nl["total"]) + " total cases\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(nl["parse_success"]) + " parser success\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(nl["grounding_success"]) + " grounding success\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(nl["argument_construction"]) + " argument construction\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(nl["reasoning_executed"]) + " reasoning executed\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(nl["decisive_verdicts"]) + " decisive verdicts, " + str(nl["unknown_verdicts"]) + " unknown")
    lines.append("\\end{minipage}}")
    lines.append("\\hfill")
    lines.append("\\fbox{\\begin{minipage}{0.47\\linewidth}")
    lines.append("\\centering")
    lines.append("\\textbf{Controlled Symbolic Pipeline (n=" + str(sym["total"]) + ")}\\\\")
    lines.append(str(sym["total"]) + " total cases\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(sym["grounding_success"]) + " grounding success\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(sym["argument_construction"]) + " argument construction\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(sym["reasoning_executed"]) + " reasoning executed\\\\")
    lines.append("$\\downarrow$\\\\")
    lines.append(str(sym["decisive_verdicts"]) + " decisive verdicts, " + str(sym["unknown_verdicts"]) + " unknown")
    lines.append("\\end{minipage}}")
    lines.append("\\caption{Pipeline-localization view: integrated NL collapses primarily at grounding, while controlled symbolic remains decisive.}")
    lines.append("\\label{fig:pipeline_localization}")
    lines.append("\\end{figure}")
    lines.append("")

    lines.append("\\subsection{Failure Distribution}")
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append("\\begin{tabular}{llrr}")
    lines.append("\\toprule")
    lines.append("Stage & Reason & Count & \\% \\\\")
    lines.append("\\midrule")
    for row in sorted(failure_distribution, key=lambda x: x.get("count", 0), reverse=True):
        lines.append(
            f"{latex_escape(str(row.get('stage','')))} & {latex_escape(str(row.get('reason','')))} & {row.get('count',0)} & {row.get('pct',0):.1f} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\caption{Execution-backed failure decomposition from emitted stage/reason labels.}")
    lines.append("\\label{tab:failure_distribution}")
    lines.append("\\end{table}")

    return "\n".join(lines) + "\n"


def main() -> int:
    summary = read_json(IN_SUMMARY)
    pipeline_rows = read_jsonl(IN_PIPELINE)
    pipeline = compute_pipeline_counts(pipeline_rows)

    OUT_PIPELINE_JSON.write_text(json.dumps(pipeline, indent=2), encoding="utf8")
    OUT_TEX.write_text(generate_tex(summary, pipeline), encoding="utf8")

    print(f"Wrote {OUT_TEX}")
    print(f"Wrote {OUT_PIPELINE_JSON}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
